"""
session_manager.py
==================
Manages experimental sessions for the eye tracking system.

Responsibilities
----------------
* Create a timestamped session directory under ``data/sessions/``.
* Generate / manage a participant code (P001, P002, …).
* Initialise the directory structure with placeholder files.
* Write and update ``metadata.json``.
* Provide a structured logging interface backed by ``session.log``.
* Track session state throughout the experiment lifecycle.
"""

from __future__ import annotations

import json
import logging
import os
import platform
import sys
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Any

# ---------------------------------------------------------------------------
# Session state
# ---------------------------------------------------------------------------

class SessionState(str, Enum):
    """Lifecycle states of an experimental session."""

    NOT_STARTED = "not_started"
    RUNNING = "running"
    COMPLETED = "completed"
    ERROR = "error"


# ---------------------------------------------------------------------------
# SessionManager
# ---------------------------------------------------------------------------

class SessionManager:
    """
    Manages a single experimental session for the eye tracking system.

    Parameters
    ----------
    base_path:
        Root directory under which ``sessions/`` are stored.  Defaults to
        ``data/sessions/`` relative to *this module's* location so that the
        path resolves correctly regardless of the process working directory.
    participant_code:
        Explicit participant code (e.g. ``"P003"``).  When *None* the next
        available code is auto-generated by scanning existing session
        directories.
    config:
        Arbitrary experiment-configuration mapping that will be embedded in
        ``metadata.json``.
    """

    #: Directory name prefix inside *base_path*.
    SESSION_PREFIX: str = "session_"
    #: Timestamp format used in the directory name.
    TIMESTAMP_FORMAT: str = "%Y%m%d_%H%M%S"
    #: Participant code format.
    _PARTICIPANT_FMT: str = "P{:03d}"

    # ------------------------------------------------------------------
    # Construction
    # ------------------------------------------------------------------

    def __init__(
        self,
        base_path: Path | str | None = None,
        participant_code: str | None = None,
        config: dict[str, Any] | None = None,
    ) -> None:
        if base_path is None:
            # Resolve relative to *this file* so callers need no knowledge of
            # the project layout.
            _module_dir = Path(__file__).resolve().parent
            base_path = _module_dir.parent / "data" / "sessions"

        self._base_path: Path = Path(base_path).resolve()
        self._config: dict[str, Any] = dict(config) if config else {}
        self._state: SessionState = SessionState.NOT_STARTED

        # Paths set by create_session()
        self._session_path: Path | None = None
        self._raw_data_path: Path | None = None
        self._processed_data_path: Path | None = None
        self._metadata_path: Path | None = None
        self._log_path: Path | None = None

        # Participant code — resolve now so callers can inspect before calling
        # create_session().
        self._participant_code: str = (
            participant_code
            if participant_code is not None
            else self._next_participant_code()
        )

        # Python logger (configured in create_session())
        self._logger: logging.Logger | None = None

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def create_session(self) -> Path:
        """
        Create the session directory tree and initialise all session files.

        Directory layout::

            data/sessions/
            └── session_YYYYMMDD_HHMMSS/
                ├── raw_data.csv
                ├── processed_data.csv
                ├── metadata.json
                └── session.log

        Returns
        -------
        Path
            Absolute path to the newly created session directory.

        Raises
        ------
        RuntimeError
            If the session has already been created.
        OSError
            If the directory cannot be created due to a filesystem error.
        """
        if self._session_path is not None:
            raise RuntimeError(
                f"Session already created at {self._session_path}. "
                "Instantiate a new SessionManager for a new session."
            )

        timestamp = datetime.now().strftime(self.TIMESTAMP_FORMAT)
        session_dir_name = f"{self.SESSION_PREFIX}{timestamp}"
        session_path = self._base_path / session_dir_name

        try:
            session_path.mkdir(parents=True, exist_ok=False)
        except FileExistsError:
            # Extremely unlikely (same-second collision); append a suffix.
            session_path = self._base_path / f"{session_dir_name}_1"
            session_path.mkdir(parents=True, exist_ok=False)

        self._session_path = session_path
        self._raw_data_path = session_path / "raw_data.csv"
        self._processed_data_path = session_path / "processed_data.csv"
        self._metadata_path = session_path / "metadata.json"
        self._log_path = session_path / "session.log"

        # Touch placeholder files so their presence is guaranteed.
        self._raw_data_path.touch()
        self._processed_data_path.touch()

        # Set up Python logging to session.log.
        self._configure_logger()

        # Write initial metadata.
        self._write_initial_metadata(timestamp)

        self._state = SessionState.RUNNING
        self.log("Session created.", level="INFO")

        return self._session_path

    # ------------------------------------------------------------------

    def log(self, message: str, level: str = "INFO") -> None:
        """
        Write a message to ``session.log`` with an ISO-8601 timestamp prefix.

        Parameters
        ----------
        message:
            Human-readable log message.
        level:
            Standard logging level name: ``'DEBUG'``, ``'INFO'``,
            ``'WARNING'``, ``'ERROR'``, ``'CRITICAL'``.  Case-insensitive.

        Raises
        ------
        RuntimeError
            If :meth:`create_session` has not been called yet.
        """
        if self._logger is None:
            raise RuntimeError(
                "Logger is not initialised. Call create_session() first."
            )

        numeric_level = getattr(logging, level.upper(), logging.INFO)
        self._logger.log(numeric_level, message)

    # ------------------------------------------------------------------

    def update_metadata(self, **kwargs: Any) -> None:
        """
        Merge *kwargs* into ``metadata.json`` and persist to disk.

        Nested values are *not* deep-merged — top-level keys are replaced
        entirely.  Call this method at any point during or after the session
        to record additional information (e.g. calibration results).

        Parameters
        ----------
        **kwargs:
            Key-value pairs to update in the metadata document.

        Raises
        ------
        RuntimeError
            If :meth:`create_session` has not been called yet.
        """
        if self._metadata_path is None:
            raise RuntimeError(
                "Metadata path is not set. Call create_session() first."
            )

        current = self._load_metadata()
        current.update(kwargs)
        self._persist_metadata(current)

    # ------------------------------------------------------------------

    def finalize_session(self) -> None:
        """
        Finalise the session: record end time, mark state as *completed*, and
        flush / close the log handler.

        Safe to call multiple times (idempotent after the first call).

        Raises
        ------
        RuntimeError
            If :meth:`create_session` has not been called yet.
        """
        if self._session_path is None:
            raise RuntimeError(
                "Cannot finalise a session that has not been created. "
                "Call create_session() first."
            )

        if self._state in (SessionState.COMPLETED, SessionState.ERROR):
            return  # Already finalised — nothing to do.

        end_time = datetime.now().isoformat()
        self.update_metadata(end_time=end_time, session_state=SessionState.COMPLETED)
        self._state = SessionState.COMPLETED
        self.log("Session finalised.", level="INFO")
        self._close_logger()

    # ------------------------------------------------------------------

    def get_session_path(self) -> Path:
        """
        Return the absolute path to the session directory.

        Raises
        ------
        RuntimeError
            If :meth:`create_session` has not been called yet.
        """
        if self._session_path is None:
            raise RuntimeError(
                "Session path is not available. Call create_session() first."
            )
        return self._session_path

    def get_raw_data_path(self) -> Path:
        """
        Return the absolute path to ``raw_data.csv``.

        Raises
        ------
        RuntimeError
            If :meth:`create_session` has not been called yet.
        """
        if self._raw_data_path is None:
            raise RuntimeError(
                "Raw data path is not available. Call create_session() first."
            )
        return self._raw_data_path

    def get_processed_data_path(self) -> Path:
        """
        Return the absolute path to ``processed_data.csv``.

        Raises
        ------
        RuntimeError
            If :meth:`create_session` has not been called yet.
        """
        if self._processed_data_path is None:
            raise RuntimeError(
                "Processed data path is not available. Call create_session() first."
            )
        return self._processed_data_path

    def get_metadata_path(self) -> Path:
        """
        Return the absolute path to ``metadata.json``.

        Raises
        ------
        RuntimeError
            If :meth:`create_session` has not been called yet.
        """
        if self._metadata_path is None:
            raise RuntimeError(
                "Metadata path is not available. Call create_session() first."
            )
        return self._metadata_path

    def get_log_path(self) -> Path:
        """
        Return the absolute path to ``session.log``.

        Raises
        ------
        RuntimeError
            If :meth:`create_session` has not been called yet.
        """
        if self._log_path is None:
            raise RuntimeError(
                "Log path is not available. Call create_session() first."
            )
        return self._log_path

    # ------------------------------------------------------------------
    # Convenience properties
    # ------------------------------------------------------------------

    @property
    def participant_code(self) -> str:
        """The participant code assigned to this session."""
        return self._participant_code

    @property
    def state(self) -> SessionState:
        """Current :class:`SessionState` of this session."""
        return self._state

    # ------------------------------------------------------------------
    # Error-state helper
    # ------------------------------------------------------------------

    def mark_error(self, reason: str = "") -> None:
        """
        Transition the session into the *error* state and record the reason.

        Parameters
        ----------
        reason:
            Short description of why the session ended in error.
        """
        if self._session_path is None:
            self._state = SessionState.ERROR
            return

        self._state = SessionState.ERROR
        try:
            self.update_metadata(
                session_state=SessionState.ERROR,
                error_reason=reason,
                error_time=datetime.now().isoformat(),
            )
            self.log(f"Session ended with error: {reason}", level="ERROR")
        finally:
            self._close_logger()

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _next_participant_code(self) -> str:
        """
        Scan existing session directories to derive the next participant code.

        The code is based on the total number of existing sessions, not on
        previously assigned participant codes, which keeps the counter simple
        and monotonic even when old sessions are deleted.
        """
        if not self._base_path.exists():
            return self._PARTICIPANT_FMT.format(1)

        existing = [
            d for d in self._base_path.iterdir()
            if d.is_dir() and d.name.startswith(self.SESSION_PREFIX)
        ]
        return self._PARTICIPANT_FMT.format(len(existing) + 1)

    # ------------------------------------------------------------------

    def _configure_logger(self) -> None:
        """Attach a file handler to a session-specific :class:`logging.Logger`."""
        logger_name = f"session.{self._session_path.name}"  # type: ignore[union-attr]
        logger = logging.getLogger(logger_name)
        logger.setLevel(logging.DEBUG)
        logger.propagate = False  # Isolate from the root logger.

        handler = logging.FileHandler(self._log_path, mode="a", encoding="utf-8")  # type: ignore[arg-type]
        formatter = logging.Formatter(
            fmt="%(asctime)s [%(levelname)s] %(message)s",
            datefmt="%Y-%m-%dT%H:%M:%S",
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)

        self._logger = logger

    def _close_logger(self) -> None:
        """Flush and remove all handlers from the session logger."""
        if self._logger is None:
            return
        for handler in list(self._logger.handlers):
            handler.flush()
            handler.close()
            self._logger.removeHandler(handler)

    # ------------------------------------------------------------------

    def _write_initial_metadata(self, timestamp: str) -> None:
        """Compose and persist the initial ``metadata.json`` document."""
        metadata: dict[str, Any] = {
            # Session identity
            "session_id": self._session_path.name,  # type: ignore[union-attr]
            "participant_code": self._participant_code,
            "session_state": SessionState.RUNNING,
            # Timing
            "start_time": datetime.now().isoformat(),
            "end_time": None,
            # System
            "os": platform.platform(),
            "python_version": sys.version,
            "gazefollower_version": self._get_gazefollower_version(),
            # Hardware (filled later via update_metadata)
            "camera_id": None,
            "resolution": None,
            # Experiment
            "calibration_info": None,
            "experiment_config": self._config,
        }
        self._persist_metadata(metadata)

    # ------------------------------------------------------------------

    @staticmethod
    def _get_gazefollower_version() -> str:
        """
        Attempt to read the installed GazeFollower package version.

        Returns ``"not_installed"`` if the package cannot be found so that
        metadata writing never raises an exception.
        """
        try:
            from importlib.metadata import version, PackageNotFoundError

            try:
                return version("gazefollower")
            except PackageNotFoundError:
                return "not_installed"
        except ImportError:
            # Python < 3.8 fallback (importlib.metadata requires 3.8+).
            try:
                import pkg_resources  # type: ignore[import]

                return pkg_resources.get_distribution("gazefollower").version
            except Exception:
                return "not_installed"

    # ------------------------------------------------------------------

    def _load_metadata(self) -> dict[str, Any]:
        """Read and deserialise ``metadata.json``."""
        try:
            return json.loads(self._metadata_path.read_text(encoding="utf-8"))  # type: ignore[union-attr]
        except (json.JSONDecodeError, OSError) as exc:
            # Do not crash the experiment; return a bare dict and log the issue.
            if self._logger is not None:
                self._logger.warning(
                    "Could not read metadata.json (%s). Starting with empty document.",
                    exc,
                )
            return {}

    def _persist_metadata(self, data: dict[str, Any]) -> None:
        """Serialise *data* and write to ``metadata.json``."""
        self._metadata_path.write_text(  # type: ignore[union-attr]
            json.dumps(data, indent=4, default=str),
            encoding="utf-8",
        )

    # ------------------------------------------------------------------
    # Dunder helpers
    # ------------------------------------------------------------------

    def __repr__(self) -> str:  # pragma: no cover
        return (
            f"<SessionManager participant={self._participant_code!r} "
            f"state={self._state.value!r} "
            f"path={self._session_path}>"
        )

    def __enter__(self) -> "SessionManager":
        self.create_session()
        return self

    def __exit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        if exc_type is not None:
            self.mark_error(reason=str(exc_val))
        else:
            self.finalize_session()
